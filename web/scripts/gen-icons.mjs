// Generates app/utils/humbleicons.ts containing only the Humbleicons the app uses,
// so the full icon set never ships to the browser.
// Run: npm run icons -w web   (re-run after using a new icon name)
import { readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const require = createRequire(import.meta.url)
const { icons } = require('@iconify-json/humbleicons/icons.json')
const root = join(dirname(fileURLToPath(import.meta.url)), '..', 'app')
const out = join(root, 'utils', 'humbleicons.ts')

const files = []
const walk = (dir) => {
  for (const f of readdirSync(dir)) {
    const p = join(dir, f)
    if (statSync(p).isDirectory()) walk(p)
    else if (/\.(vue|ts)$/.test(f) && p !== out) files.push(p)
  }
}
walk(root)

const used = new Set()
for (const file of files) {
  for (const [, token] of readFileSync(file, 'utf8').matchAll(/['"]([a-z0-9-]+)['"]/g)) {
    if (icons[token]) used.add(token)
  }
}

const names = [...used].sort()
const body = names.map((n) => `  '${n}': ${JSON.stringify(icons[n].body)},`).join('\n')
writeFileSync(
  out,
  `// AUTO-GENERATED by scripts/gen-icons.mjs — do not edit by hand.\n// Humbleicons (MIT) https://github.com/zraly/humbleicons\n\nexport const humbleicons = {\n${body}\n} as const\n\nexport type HumbleIconName = keyof typeof humbleicons\n`,
)
console.log(`humbleicons: ${names.length} icons → ${out}`)
